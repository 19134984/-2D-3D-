#!/usr/bin/env bash
#
# Pre-render helper for the OpenLB user guide.
#
# The documentation for each example lives next to its code, as
# examples/<category>/.../<example>/<example>.qmd. Most examples sit directly
# in their category, but some are grouped further -- the structural mechanics
# cases for instance live in
# examples/structuralmechanics/linearElasticity/quasistationary/<example>/ --
# so the whole category subtree is searched. Quarto can only include files that
# sit inside the project directory, so this script mirrors every such file into
# doc/examples/ as a symlink and writes the include list used by the PDF
# build.
#
# A mirrored page keeps its place in the source tree, so every example gets a
# directory of its own below doc/examples/, which holds the page and, if the
# example has figures, its doc/ directory:
#
#   examples/laminar/cavity2d/cavity2d.qmd
#     -> doc/examples/laminar/cavity2d/cavity2d.qmd
#   examples/laminar/cavity2d/doc
#     -> doc/examples/laminar/cavity2d/doc
#   examples/structuralmechanics/linearElasticity/quasistationary/periodicPlate/periodicPlate.qmd
#     -> doc/examples/structuralmechanics/linearElasticity/quasistationary/periodicPlate/periodicPlate.qmd
#
# Keeping the intermediate directories is what tells the two periodicPlate
# examples of structuralmechanics apart. A page refers to its figures by a
# project absolute path such as
# /examples/laminar/cavity2d/doc/fig/cavity2dDomain.svg.
#
# Both artefacts are generated, which is why they are listed in .gitignore --
# the symlinks never have to be committed. The script is registered as a
# pre-render script in _quarto.yml and _quarto-book.yml, so a plain
# `quarto render` regenerates them automatically. It is idempotent and can
# also be run by hand.

set -euo pipefail

doc_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
examples_dir="$doc_dir/examples"
src_dir="$(cd "$doc_dir/.." && pwd)/examples"
includes="$examples_dir/_includes.qmd"

if [ ! -d "$src_dir" ]; then
  echo "link_examples: no example sources at $src_dir" >&2
  exit 1
fi

# Lists the documentation of one category, as paths relative to the category
# directory. Pages are grouped by the directory of the category they sit in
# and, within a group, ordered from the shallowest to the deepest, so that an
# overview page such as linearElasticity/linearElasticity.qmd is emitted before
# the sub-examples it introduces.
category_docs() {
  local dir="$1" doc
  find "$dir" -mindepth 2 -name '*.qmd' | while IFS= read -r doc; do
    printf '%s\n' "${doc#"$dir"}"
  done | awk -F/ '{ printf "%s\t%d\t%s\n", $1, NF, $0 }' \
       | sort -t"$(printf '\t')" -k1,1 -k2,2n -k3,3 \
       | cut -f3-
}

# Drop symlinks from a previous run so that renamed or removed examples do not
# linger, and clear out the directories that held them. Real files (figures,
# hand written pages) are left untouched, and so are the category directories.
find "$examples_dir" -type l -name '*.qmd' -delete
find "$examples_dir" -type l -name doc -delete
find "$examples_dir" -mindepth 2 -type d -empty -delete

tmp_includes="$(mktemp)"
tmp_sidebar="$(mktemp)"
trap 'rm -f "$tmp_includes" "$tmp_sidebar" "$tmp_sidebar.yml"' EXIT

{
  echo "<!-- Generated by link_examples.sh -- do not edit. -->"
  echo
} >"$tmp_includes"

echo "            # BEGIN examples (generated by link_examples.sh -- do not edit by hand)" >"$tmp_sidebar"

linked=0
for category_path in "$src_dir"/*/; do
  category="$(basename "$category_path")"

  # Collect the documented examples of this category first, so that a category
  # heading is only emitted when there is something to put under it.
  mapfile -t docs < <(category_docs "$category_path")
  if [ "${#docs[@]}" -eq 0 ]; then
    continue
  fi

  mkdir -p "$examples_dir/$category"
  # The labels give the overview table in the PDF (example_table.py) fixed
  # targets for its \ref's: excat:<category> for the category and
  # ex:<path> for every example, see below.
  {
    echo "## $category"
    echo
    echo '```{=latex}'
    echo "\\label{excat:$category}"
    echo '```'
    echo
  } >>"$tmp_includes"

  # A category may carry a hand written introduction, which is placed directly
  # below its heading. These live in doc/ and are committed as usual.
  if [ -f "$examples_dir/$category/_intro.qmd" ]; then
    echo "{{< include $category/_intro.qmd >}}" >>"$tmp_includes"
  fi

  echo "            - section: \"$category\"" >>"$tmp_sidebar"
  echo "              contents:" >>"$tmp_sidebar"

  for doc in "${docs[@]}"; do
    # The page is mirrored at the place it has in the source tree, into a
    # directory of its own named after the example, where the example's doc/
    # directory goes as well.
    example="$(dirname "$doc")"
    rel="$category/$doc"

    # The layout is fixed, so the relative target can be spelled out rather than
    # derived with realpath --relative-to, which is GNU-only. A link has to climb
    # out of doc/examples/, out of the category directory and out of every
    # directory between the category and the example, the example's own
    # directory included.
    up="../../.."
    IFS=/ read -r -a parts <<<"$example"
    for _ in "${parts[@]}"; do
      up="../$up"
    done

    link="$examples_dir/$rel"

    # A hand written page of the same name takes precedence over the source
    # tree copy, so an existing regular file is never overwritten.
    if [ -e "$link" ] && [ ! -L "$link" ]; then
      echo "link_examples: keeping existing file $link" >&2
    else
      mkdir -p "$(dirname "$link")"
      ln -sfn "$up/examples/$category/$doc" "$link"
      linked=$((linked + 1))
    fi

    # The figures of the example, if it has any, next to its page.
    if [ -d "$category_path$example/doc" ]; then
      figures="$examples_dir/$category/$example/doc"
      if [ -e "$figures" ] && [ ! -L "$figures" ]; then
        echo "link_examples: keeping existing directory $figures" >&2
      else
        mkdir -p "$(dirname "$figures")"
        ln -sfn "$up/examples/$category/$example/doc" "$figures"
      fi
    fi

    # The example's heading comes from the included file, so its label cannot
    # be written here. The div hands it to include/example_labels.lua, which
    # puts it right after that heading. Quarto's own heading ids are no use as
    # targets: they are derived from the heading text, and several examples
    # share a name.
    {
      echo "::: {.olb-example label=\"ex:${rel%.qmd}\"}"
      echo
      echo "{{< include $rel >}}"
      echo
      echo ":::"
      echo
    } >>"$tmp_includes"
    echo "                - examples/$rel" >>"$tmp_sidebar"
  done

  echo >>"$tmp_includes"
done

echo "            # END examples" >>"$tmp_sidebar"

mv "$tmp_includes" "$includes"

# The website sidebar lists every example page explicitly. Glob patterns would
# express the same thing far more briefly, but Quarto resolves a sidebar glob
# against the whole project input list, which makes rendering the examples
# landing page take minutes instead of seconds. The list is therefore generated
# here and committed as part of _quarto.yml.
#
# Quarto reads _quarto.yml before it runs this script, so a change to the list
# only takes effect on the next render. That only matters when examples are
# added or removed, and the message below says when it happened.
sidebar="$doc_dir/_quarto.yml"

awk -v block="$tmp_sidebar" '
  /# BEGIN examples \(generated by link_examples.sh/ { skip = 1; while ((getline line < block) > 0) print line; next }
  /# END examples$/ { skip = 0; next }
  !skip { print }
' "$sidebar" >"$tmp_sidebar.yml"

if cmp -s "$tmp_sidebar.yml" "$sidebar"; then
  rm -f "$tmp_sidebar.yml"
else
  mv "$tmp_sidebar.yml" "$sidebar"
  echo "link_examples: updated the example list in _quarto.yml -- commit it; it applies from the next render" >&2
fi

trap - EXIT
rm -f "$tmp_sidebar"

echo "link_examples: linked $linked example pages, wrote $(basename "$includes")"
