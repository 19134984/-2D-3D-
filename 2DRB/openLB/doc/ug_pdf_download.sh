#!/usr/bin/env bash
#
# Adds the "download the user guide as PDF" tool to the website navbar.
#
# The PDF is built by a separate render (`quarto render --profile book --to
# pdf`) and lands in the book output directory, which the website build
# ignores. This script bridges the two: it copies the PDF into the rendered
# site and writes include/pdf_download.html, which puts a download button next
# to the GitLab icon in the navbar. When no PDF has been built, the include is
# written empty and the website looks exactly as before.
#
# The button cannot be listed under `website.navbar.tools` in _quarto.yml
# because Quarto reads that file before it runs any pre-render script, so a
# generated entry would only take effect on the following render. The include
# file, on the other hand, is read while the pages are rendered and therefore
# always reflects the PDF that is on disk right now.
#
# The script is registered both as a pre-render and as a post-render script in
# _quarto.yml: the pre-render pass has to write the include before the pages
# are rendered, and the post-render pass copies the PDF once the output
# directory exists. It is idempotent and can also be run by hand.

set -euo pipefail

quarto_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
site_config="$quarto_dir/_quarto.yml"
book_config="$quarto_dir/_quarto-book.yml"
include="$quarto_dir/include/pdf_download.html"

# The name the download is offered under, independent of how the book output
# file happens to be called.
download_name="openlb-userguide.pdf"

# Reads a scalar from a Quarto config. The keys looked up below (output-dir,
# output-file) occur exactly once per file, so matching them anywhere in the
# document is enough and saves parsing the nesting.
yaml_value() {
  sed -n "s/^[[:space:]]*$1:[[:space:]]*[\"']\{0,1\}\([^\"'#]*[^\"' #]\)[\"']\{0,1\}[[:space:]]*$/\1/p" "$2" | head -n 1
}

site_dir="$quarto_dir/$(yaml_value output-dir "$site_config")"
pdf_dir_name="$(yaml_value output-dir "$book_config")"
pdf_dir="$quarto_dir/$pdf_dir_name"

# A book names its PDF after book.output-file and falls back to the book
# title, so the name cannot be read off the config with any confidence -- the
# format.pdf output-file key that would give it for an ordinary document is
# ignored for books. Take what the book render actually left behind instead,
# the newest one should the name ever change.
pdf=""
for candidate in "$pdf_dir"/*.pdf; do
  if [ -f "$candidate" ] && { [ -z "$pdf" ] || [ "$candidate" -nt "$pdf" ]; }; then
    pdf="$candidate"
  fi
done

if [ -z "$pdf" ]; then
  cat >"$include" <<'EOF'
<!-- Generated by ug_pdf_download.sh -- do not edit. -->
<!-- No user guide PDF has been built, so the navbar shows no download tool. -->
EOF
  echo "ug_pdf_download: no PDF in $pdf_dir_name, wrote an empty $(basename "$include")"
  exit 0
fi

# The PDF is served from the same relative path it has in the project, so that
# the site keeps the ug_pdf/<file>.pdf layout of the source tree.
href="$pdf_dir_name/$(basename "$pdf")"

cat >"$include" <<EOF
<!-- Generated by ug_pdf_download.sh -- do not edit. -->
<script>
  (function () {
    var href = "$href";
    var download = "$download_name";
EOF

cat >>"$include" <<'EOF'

    // Pages sit at different depths, so the link has to be built relative to
    // the site root. Quarto states the offset in a meta tag; the navbar brand,
    // which always points at the root index page, is the fallback.
    function siteRoot() {
      var meta = document.querySelector('meta[name="quarto:offset"]');
      if (meta && meta.content) {
        return meta.content.replace(/\/?$/, "/");
      }
      var brand = document.querySelector("a.navbar-brand");
      if (brand) {
        return brand.getAttribute("href").replace(/index\.html$/, "");
      }
      return "";
    }

    // The GitLab tool is rendered once per navbar layout (the icon row on wide
    // screens, the collapsed menu on narrow ones). Cloning it picks up the
    // classes of whichever layout it belongs to, so the download button is
    // styled and placed like its neighbours in both.
    function addDownloadTool() {
      var root = siteRoot();
      var anchors = document.querySelectorAll(
        '.navbar a[href*="gitlab.com"], header a[href*="gitlab.com"]'
      );

      Array.prototype.forEach.call(anchors, function (anchor) {
        var previous = anchor.previousElementSibling;
        if (previous && previous.classList.contains("olb-pdf-download")) {
          return;
        }

        var tool = anchor.cloneNode(true);
        tool.classList.add("olb-pdf-download");
        tool.setAttribute("href", root + href);
        tool.setAttribute("download", download);
        tool.setAttribute("title", "Download the user guide as PDF");
        tool.setAttribute("aria-label", "Download the user guide as PDF");
        tool.removeAttribute("target");
        tool.removeAttribute("rel");

        var icon = tool.querySelector("i");
        if (icon) {
          icon.className = "bi bi-file-earmark-pdf";
        }
        // The collapsed menu labels its entries; the icon row does not.
        Array.prototype.forEach.call(tool.childNodes, function (node) {
          if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
            node.textContent = " User Guide (PDF)";
          }
        });

        anchor.parentNode.insertBefore(tool, anchor);
      });
    }

    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", addDownloadTool);
    } else {
      addDownloadTool();
    }
  })();
</script>
EOF

echo "ug_pdf_download: wrote $(basename "$include") for $href"

# Only the post-render pass finds the site directory in place; during
# pre-render of a first build there is nothing to copy into yet.
if [ -d "$site_dir" ]; then
  mkdir -p "$site_dir/$pdf_dir_name"
  cp "$pdf" "$site_dir/$pdf_dir_name/"
  echo "ug_pdf_download: copied $(basename "$pdf") into $(basename "$site_dir")/$pdf_dir_name"
fi
