// test second iteration
TEST(AnisoDiscr, testSecondIteration)
{
  int const  q = descriptors::D3Q27DescriptorLebedev::q - 1;
  double solution[q*(q+1)/2];
  std::array<std::array<double,q>,q> phi;
  computeAnisotropyMatrix<descriptors::D3Q27DescriptorLebedev>( 1e-4, 0.1, solution, phi, 3 );
  for ( int i = 0; i < q*(q+1)/2; i++ ) {
    ASSERT_NEAR(solution[i], matlab2[i], 1e-8) << "iter " << i+1;
  }
}

